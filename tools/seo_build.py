def jsonld(pg, lang):
    url = SITE + L(pg['path'], lang)
    person = {'@type': 'Person', '@id': SITE + '/#person', 'name': 'Sardor Badalov',
              'jobTitle': 'Lead Designer / Art Director', 'url': SITE + '/',
              'address': {'@type': 'PostalAddress', 'addressLocality': 'Tashkent', 'addressCountry': 'UZ'},
              'sameAs': [LINKEDIN, BEHANCE]}
    site = {'@type': 'WebSite', '@id': SITE + '/#website', 'url': SITE + '/', 'name': BRAND,
            'inLanguage': ['en', 'ru'], 'publisher': {'@id': SITE + '/#person'}}
    ptype = {'about': 'ProfilePage', 'work': 'CollectionPage', 'gallery': 'CollectionPage', 'case': 'CollectionPage'}.get(pg['kind'], 'WebPage')
    page = {'@type': ptype, '@id': url + '#webpage', 'url': url, 'name': pg['title'][0 if lang == 'en' else 1],
            'description': pg['desc'][0 if lang == 'en' else 1], 'inLanguage': lang,
            'isPartOf': {'@id': SITE + '/#website'}, 'primaryImageOfPage': SITE + pg['image']}
    if pg['kind'] == 'about':
        page['mainEntity'] = {'@id': SITE + '/#person'}
    graph = [site, person, page]
    if pg['kind'] == 'project':
        graph.append({'@type': 'CreativeWork', '@id': url + '#work', 'name': pg['crumbs'][-1][1],
                      'description': pg['desc'][0 if lang == 'en' else 1], 'url': url, 'image': SITE + pg['image'],
                      'inLanguage': lang, 'creator': {'@id': SITE + '/#person'}})
    if pg['crumbs']:
        items = [('/', 'Home', 'Главная')] + pg['crumbs']
        graph.append({'@type': 'BreadcrumbList', 'itemListElement': [
            {'@type': 'ListItem', 'position': i + 1, 'name': (e if lang == 'en' else r), 'item': SITE + L(pth, lang)}
            for i, (pth, e, r) in enumerate(items)]})
        page['breadcrumb'] = {'@id': url + '#breadcrumb'}
        graph[-1]['@id'] = url + '#breadcrumb'
    return json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False).replace('</', '<\\/')


