def trim(s, n=158):
    s = re.sub(r'\s+', ' ', str(s or '')).strip()
    if len(s) <= n:
        return s
    cut = s[:n]
    k = max(cut.rfind('. '), cut.rfind('! '), cut.rfind('? '))
    if k > 70:
        return cut[:k + 1]
    return cut[:cut.rfind(' ')].rstrip(',;:—- ') + '…'


