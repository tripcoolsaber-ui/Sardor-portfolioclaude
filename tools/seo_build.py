def og_image(src, key):
    if not src:
        return '/og-share.jpg'
    if key in OG_DONE:
        return OG_DONE[key]
    try:
        from PIL import Image, ImageFilter
    except ImportError:
        return '/' + src
    dst = 'og/%s.jpg' % key
    full_src = os.path.join(ROOT, src)
    full_dst = os.path.join(ROOT, dst)
    stamp = hashlib.md5(open(full_src, 'rb').read()).hexdigest()[:10]
    if not (os.path.exists(full_dst) and OG_STAMPS.get(dst) == stamp):
        im = Image.open(full_src).convert('RGB')
        W, H = 1200, 630
        r = im.width / im.height
        if 1.55 <= r <= 2.1:         # wide covers: fill, trim only a little at the edges
            if r > W / H:
                nw = int(im.height * W / H); x0 = (im.width - nw) // 2
                im2 = im.crop((x0, 0, x0 + nw, im.height))
            else:
                nh = int(im.width * H / W); y0 = (im.height - nh) // 2
                im2 = im.crop((0, y0, im.width, y0 + nh))
            out = im2.resize((W, H), Image.LANCZOS)
        else:                          # tall or square art: whole image on the site's dark background
            px = [im.getpixel((x, y)) for x in (0, im.width - 1) for y in (0, im.height // 2, im.height - 1)]
            bg = tuple(sum(c[j] for c in px) // len(px) for j in range(3))  # the picture's own edge colour, so no visible frame
            out = Image.new('RGB', (W, H), bg)
            k = min(W * .92 / im.width, H * .92 / im.height)
            fg = im.resize((max(1, int(im.width * k)), max(1, int(im.height * k))), Image.LANCZOS)
            out.paste(fg, ((W - fg.width) // 2, (H - fg.height) // 2))
        os.makedirs(os.path.dirname(full_dst), exist_ok=True)
        out.save(full_dst, 'JPEG', quality=86, optimize=True, progressive=True)
        OG_STAMPS[dst] = stamp
    OG_DONE[key] = '/' + dst
    return OG_DONE[key]


