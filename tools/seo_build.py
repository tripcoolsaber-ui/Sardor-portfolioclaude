def dl(rows, lang):
    rows = [(k, v) for k, v in rows if v]
    if not rows:
        return ''
    return '<dl>%s</dl>' % ''.join('<dt>%s</dt><dd>%s</dd>' % (esc(tr(k, lang)), esc(tr(v, lang))) for k, v in rows)


