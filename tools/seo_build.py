def render(pg, lang):
    s = TPL
    s = re.sub(r'<!--seo:head-->.*?<!--/seo:head-->', lambda m_: '<!--seo:head-->' + head(pg, lang) + '<!--/seo:head-->', s, count=1, flags=re.S)
    s = re.sub(r'<!--seo:body-->.*?<!--/seo:body-->', lambda m_: '<!--seo:body-->' + body(pg, lang) + '<!--/seo:body-->', s, count=1, flags=re.S)
    s = re.sub(r'<html lang="[a-z]+"', '<html lang="%s"' % lang, s, count=1)
    return s


